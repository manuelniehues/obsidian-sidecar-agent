const TABLES = { en: EN, de: DE };

function detectLanguage() {
  return (obsidian.getLanguage?.() || "en").toLowerCase().split("-")[0];
}

let LANG = TABLES[detectLanguage()] ? detectLanguage() : "en";

/** "" = follow Obsidian, otherwise "en" or "de". Applies to text rendered afterwards. */
export function setLanguage(code) {
  const c = code || detectLanguage();
  LANG = TABLES[c] ? c : "en";
}

/** Locale for date and time formatting. */
export function locale() {
  return LANG === "de" ? "de-DE" : "en-US";
}

/** Translated text for a key, with {placeholders} filled from vars. */
export function t(key, vars) {
  const s = TABLES[LANG][key] ?? EN[key] ?? key;
  return vars ? s.replace(/\{(\w+)\}/g, (m, k) => (vars[k] !== undefined ? String(vars[k]) : m)) : s;
}

